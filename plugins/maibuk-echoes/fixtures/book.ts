/** A seeded PRNG (mulberry32): the same seed gives the same Book every run. */
export function mulberry32(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4_294_967_296;
  };
}

/** Zipf-ish weighting: rank 1 is picked far more often than the last rank. */
function weightedPicker(vocabulary: readonly string[], rand: () => number): () => string {
  const cumulative: number[] = [];
  let total = 0;
  for (let rank = 0; rank < vocabulary.length; rank++) {
    total += 1 / (rank + 1);
    cumulative.push(total);
  }
  return () => {
    const target = rand() * total;
    let low = 0;
    let high = cumulative.length - 1;
    while (low < high) {
      const mid = (low + high) >> 1;
      if (cumulative[mid] < target) low = mid + 1;
      else high = mid;
    }
    return vocabulary[low];
  };
}

/** One Chapter: sentences of 8-20 words, a paragraph break every six of them. */
function buildChapter(rand: () => number, vocabulary: readonly string[]): string {
  const pick = weightedPicker(vocabulary, rand);
  const parts: string[] = [];
  let written = 0;
  let sentences = 0;
  while (written < CHAPTER_WORDS) {
    const length = Math.min(8 + Math.floor(rand() * 13), CHAPTER_WORDS - written);
    const sentence: string[] = [];
    for (let index = 0; index < length; index++) sentence.push(pick());
    parts.push(`${sentence.join(" ")}. `);
    written += length;
    sentences += 1;
    if (sentences % 6 === 0) parts.push("\n");
  }
  return parts.join("");
}

/** A Book: `BOOK_CHAPTERS` Chapters of `CHAPTER_WORDS` words, from one seed. */
export function buildEchoBook(vocabulary: readonly string[], seed: number): string[] {
  const rand = mulberry32(seed);
  const book: string[] = [];
  for (let chapter = 0; chapter < BOOK_CHAPTERS; chapter++) {
    book.push(buildChapter(rand, vocabulary));
  }
  return book;
}
