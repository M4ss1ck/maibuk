/**
 * Deterministic Book generator for the Echoes performance lane. It builds the
 * 100,000-word Book two languages share: 20 Chapters of 5,000 words each, drawn
 * from a small real vocabulary so words and phrases come back often enough to
 * exercise every kind of Echo. Everything runs off a seeded PRNG, so a run is
 * byte for byte the same on every machine.
 *
 * The vocabularies are ordered by how often a word is used: the first rows are
 * a language's most frequent words, and a handful of content words ride high in
 * them the way "word", "time", or "gente" do in a real corpus, so Overused
 * words have something to flag. Weighting falls off as 1/rank (Zipf-ish).
 */

